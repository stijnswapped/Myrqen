import fs from "node:fs/promises";
import path from "node:path";
import type { Candidate } from "./types.js";
import type { Advisory, AdvisoryRange } from "./dependencies/advisory-types.js";
import { ADVISORY_SNAPSHOT } from "./dependencies/advisory-snapshot.js";
import { readLockfile, type InstalledPackage } from "./dependencies/lockfiles.js";
import { compare, declaredRangeCertainlyAffected, inRange, parseVersion, type Version } from "./dependencies/semver.js";
import { DependencyUsage, type Site } from "./dependencies/usage.js";

export { DependencyUsage } from "./dependencies/usage.js";

/**
 * Known-vulnerable dependencies, reported by whether the application reaches them.
 *
 * ADR 019 records the design. In one paragraph: installed versions come from the
 * lockfile (the manifest is a fallback, and only an exact pin or a range that cannot
 * resolve past the fix counts as affected without one); they are compared against an
 * offline snapshot of OSV/GitHub advisories generated by `pnpm advisories:update`, so
 * a scan makes no network request; and a finding is raised only where application
 * code imports and uses the export the advisory names. Everything else is listed in
 * one informational candidate as present but not reached — never dropped, because a
 * reader deciding whether to upgrade needs to see it, and never ranked beside a
 * reached one, because a reader deciding what to fix first needs to see that too.
 */

interface Affected {
  name: string;
  version: string;
  dev: boolean;
  direct: boolean;
  advisories: Advisory[];
  /** First release outside every advisory range this version is in, or null when the data does not say. */
  fixedIn: string | null;
}

interface Reached {
  entry: Affected;
  advisories: Array<{ advisory: Advisory; site: Site; via: string; strength: "export" | "member" }>;
}

export interface DependencyAssessment {
  candidates: Candidate[];
  /** Coverage notes: what the dependency check could not establish. */
  notes: string[];
}

const SEVERITY_RANK = { critical: 4, high: 3, medium: 2, low: 1 } as const;

export async function assessDependencies(repoRoot: string, usage: DependencyUsage = new DependencyUsage()): Promise<DependencyAssessment> {
  let manifest: { dependencies?: Record<string, string>; devDependencies?: Record<string, string>; optionalDependencies?: Record<string, string> };
  try {
    manifest = JSON.parse(await fs.readFile(path.join(repoRoot, "package.json"), "utf8"));
  } catch {
    return { candidates: [], notes: [] };
  }
  const runtimeDeclared = { ...(manifest.optionalDependencies ?? {}), ...(manifest.dependencies ?? {}) };
  const devDeclared = manifest.devDependencies ?? {};
  const declaredNames = new Set([...Object.keys(runtimeDeclared), ...Object.keys(devDeclared)]);

  const lock = await readLockfile(repoRoot);
  const notes: string[] = lock.note ? [lock.note] : [];
  const byPackage = advisoriesByPackage();
  const affected: Affected[] = [];
  let possibly = 0;

  if (lock.packages.length > 0) {
    for (const installed of lock.packages) {
      const hits = affectingVersion(byPackage.get(installed.name), installed);
      if (hits.length === 0) continue;
      affected.push({
        name: installed.name,
        version: installed.version,
        // The lockfile's own flag when it has one; otherwise what the manifest says.
        dev: installed.dev || (installed.name in devDeclared && !(installed.name in runtimeDeclared)),
        direct: declaredNames.has(installed.name),
        advisories: hits,
        fixedIn: fixedIn(installed.name, installed.version)
      });
    }
  } else {
    for (const [scope, entries] of [["runtime", runtimeDeclared], ["development", devDeclared]] as const) {
      for (const [name, spec] of Object.entries(entries)) {
        const hits: Advisory[] = [];
        for (const advisory of byPackage.get(name) ?? []) {
          const verdict = declaredRangeCertainlyAffected(String(spec), advisory.ranges);
          if (verdict === "affected") hits.push(advisory);
          if (verdict === "possibly") possibly += 1;
        }
        if (hits.length === 0) continue;
        const version = /\d+\.\d+\.\d+[^\s]*/.exec(String(spec))?.[0] ?? String(spec);
        affected.push({ name, version, dev: scope === "development", direct: true, advisories: hits, fixedIn: fixedIn(name, version) });
      }
    }
    if (possibly > 0) {
      notes.push(
        `No lockfile was found, so installed versions are unknown. ${possibly} advisory match(es) apply to a declared version range that may also resolve to a fixed release; they were not reported. Commit a lockfile so the dependency check can compare what is actually installed.`
      );
    }
  }

  if (affected.length === 0) return { candidates: [], notes };

  const reached: Reached[] = [];
  const unreached: Array<{ entry: Affected; why: string }> = [];
  for (const entry of affected) {
    const hits = reachedAdvisories(entry, usage);
    if (hits.length > 0) reached.push({ entry, advisories: hits });
    const reachedIds = new Set(hits.map((hit) => hit.advisory.id));
    const rest = entry.advisories.filter((advisory) => !reachedIds.has(advisory.id));
    if (rest.length > 0) unreached.push({ entry: { ...entry, advisories: rest }, why: unreachedReason(entry, rest, usage) });
  }

  const candidates: Candidate[] = reached.map((hit) => reachedCandidate(hit));
  if (unreached.length > 0) candidates.push(unreachedCandidate(unreached, lock.file));
  return { candidates, notes };
}

/** Kept for callers that only want candidates. */
export async function analyzeDependencies(repoRoot: string, usage?: DependencyUsage): Promise<Candidate[]> {
  return (await assessDependencies(repoRoot, usage)).candidates;
}

let byPackageCache: Map<string, Advisory[]> | null = null;

function advisoriesByPackage(): Map<string, Advisory[]> {
  if (byPackageCache) return byPackageCache;
  const map = new Map<string, Advisory[]>();
  for (const advisory of ADVISORY_SNAPSHOT.advisories) {
    const list = map.get(advisory.package) ?? [];
    list.push(advisory);
    map.set(advisory.package, list);
  }
  byPackageCache = map;
  return map;
}

/**
 * First fixed releases for the few cases the snapshot cannot answer: an advisory range
 * with no `fixed` bound (OSV records `last_affected` when no fix was published on that
 * line). These are the versions the CLI's deterministic fix used before the snapshot
 * existed. One is used only when the snapshot confirms it is outside every range.
 */
const FIXED_IN_FALLBACK: Readonly<Record<string, string>> = Object.freeze({
  lodash: "4.17.21",
  minimist: "1.2.6",
  axios: "0.21.2",
  "node-fetch": "2.6.7",
  semver: "7.5.2",
  tar: "6.1.9",
  ws: "7.5.10",
  jsonwebtoken: "9.0.0",
  express: "4.18.2"
});

/** Steps of "move to the highest fix, then check again" before giving up. */
const FIXED_IN_MAX_STEPS = 16;

function rangesContaining(advisories: readonly Advisory[], version: Version): AdvisoryRange[] {
  return advisories.flatMap((advisory) => advisory.ranges.filter((range) => inRange(version, range)));
}

/**
 * The first release of `name` that lies outside every advisory range in the snapshot,
 * starting from the installed `version`: the highest `fixed` bound among the ranges the
 * version is in, repeated in case that release falls inside another advisory's range.
 * Null when the version is not affected, or when a range has no published fix and no
 * fallback release is known to clear every range.
 *
 * This is the release a mechanical upgrade moves to. Whether that crosses a major
 * version, and is therefore an API change, is the caller's decision.
 */
export function fixedIn(name: string, version: string): string | null {
  const advisories = advisoriesByPackage().get(name);
  let current = parseVersion(version);
  if (!advisories || !current) return null;
  let answer: string | null = null;
  for (let step = 0; step < FIXED_IN_MAX_STEPS; step += 1) {
    const containing = rangesContaining(advisories, current);
    if (containing.length === 0) return answer;
    if (containing.some((range) => !range.fixed)) return fallbackFixedIn(name, advisories, current);
    let highest: { text: string; version: Version } | null = null;
    for (const range of containing) {
      const fixed = parseVersion(range.fixed!);
      if (fixed && (!highest || compare(fixed, highest.version) > 0)) highest = { text: range.fixed!, version: fixed };
    }
    if (!highest || compare(highest.version, current) <= 0) return null;
    answer = highest.text;
    current = highest.version;
  }
  return null;
}

function fallbackFixedIn(name: string, advisories: readonly Advisory[], current: Version): string | null {
  const text = FIXED_IN_FALLBACK[name];
  const fallback = text ? parseVersion(text) : null;
  if (!text || !fallback || compare(fallback, current) <= 0) return null;
  return rangesContaining(advisories, fallback).length === 0 ? text : null;
}

function affectingVersion(advisories: Advisory[] | undefined, installed: InstalledPackage): Advisory[] {
  if (!advisories) return [];
  const version = parseVersion(installed.version);
  if (!version) return [];
  return advisories.filter((advisory) => advisory.ranges.some((range) => inRange(version, range)));
}

/** Advisories whose curated exports, subpaths, or members the application uses. */
function reachedAdvisories(entry: Affected, usage: DependencyUsage): Reached["advisories"] {
  const used = usage.exports.get(entry.name);
  const imported = usage.imports.has(entry.name);
  const out: Reached["advisories"] = [];
  for (const advisory of entry.advisories) {
    let found: { site: Site; via: string; strength: "export" | "member" } | null = null;
    for (const name of [...(advisory.exports ?? []), ...(advisory.subpaths ?? [])]) {
      const site = used?.get(name);
      if (site && (!found || earlier(site, found.site))) {
        found = { site, via: name.includes("/") ? `the \`${name}\` module` : name === "default" ? "the module's default export" : `\`${name}\``, strength: "export" };
      }
    }
    if (!found && imported && advisory.members) {
      for (const member of advisory.members) {
        const site = usage.memberCalls.get(member);
        if (site && (!found || earlier(site, found.site))) found = { site, via: `a \`.${member}()\` call`, strength: "member" };
      }
    }
    if (found) out.push({ advisory, ...found });
  }
  return out;
}

function unreachedReason(entry: Affected, rest: Advisory[], usage: DependencyUsage): string {
  if (!usage.imports.has(entry.name)) return entry.direct ? "declared but not imported by application code" : "installed as a dependency of another package";
  if (rest.every((advisory) => !advisory.exports && !advisory.subpaths && !advisory.members)) {
    return "imported; which of its functions are affected is not recorded, so reachability was not established";
  }
  return "imported, but the affected functions are not called from application code";
}

function reachedCandidate(hit: Reached): Candidate {
  const { entry } = hit;
  const ordered = [...hit.advisories].sort(
    (a, b) => SEVERITY_RANK[b.advisory.severity] - SEVERITY_RANK[a.advisory.severity] || a.advisory.id.localeCompare(b.advisory.id)
  );
  const first = ordered.reduce((best, item) => (earlier(item.site, best.site) ? item : best));
  const worst = ordered[0]!.advisory.severity;
  const onlyMembers = ordered.every((item) => item.strength === "member");
  // The advisory's own rating assumes an attacker controls the input to the affected
  // function. Calling it is necessary for that and not sufficient, so the rating is
  // capped at high; a match on a method name alone is capped at medium.
  const ceiling = onlyMembers ? "medium" : "high";
  const severity = SEVERITY_RANK[worst] > SEVERITY_RANK[ceiling] ? ceiling : worst;
  const ids = ordered.map((item) => advisoryLabel(item.advisory));
  const cwe = [...new Set(ordered.flatMap((item) => item.advisory.cwe))].sort();

  return {
    ruleId: "dependency-advisory-reachable",
    category: "dependency_with_known_advisory",
    title: `${entry.name}@${entry.version} is inside ${ordered.length === 1 ? "an advisory range" : `${ordered.length} advisory ranges`} and the affected code is called by the application`,
    severity,
    verification: "needs_review",
    summary: `${entry.name}@${entry.version}${entry.dev ? " (a development dependency)" : ""} is affected by ${ordered
      .slice(0, 4)
      .map((item) => `${advisoryLabel(item.advisory)} — ${item.advisory.summary}`)
      .join("; ")}${ordered.length > 4 ? `; and ${ordered.length - 4} more` : ""}. Application code reaches ${first.via} at ${first.site.file}:${first.site.line}${
      onlyMembers ? ", matched by method name, which is weaker evidence than an import of the affected export" : ""
    }. Whether a caller controls the input that triggers the defect was not determined.`,
    impact:
      "If request data reaches the affected function in the way the advisory describes, the published impact applies directly to this application. Because the function is called, upgrading is not optional hygiene here.",
    remediation: `Upgrade ${entry.name} to a release outside every listed range${entry.fixedIn ? ` (${entry.fixedIn} or later)` : ""} and run the tests. If an upgrade is blocked, confirm that no caller-controlled value reaches the call at ${first.site.file}:${first.site.line} and record why.`,
    verificationPlan: `Confirm the installed version (\`npm ls ${entry.name}\` or the lockfile), then read the advisory and decide whether input to the call at ${first.site.file}:${first.site.line} is caller-controlled. After upgrading, re-run the scan and confirm this finding is gone.`,
    taxonomy: ["CWE-1395", "CWE-1104", "OWASP-A06", ...cwe].slice(0, 16),
    location: { file: first.site.file, line: first.site.line },
    ...(first.site.route ? { route: first.site.route } : {}),
    evidence: [
      {
        kind: "dependency",
        description: `${entry.name}@${entry.version} matches ${ids.join(", ")} in the offline advisory snapshot (newest record ${ADVISORY_SNAPSHOT.newestRecord ?? "unknown"}).${fixedInPhrase(entry)}`,
        location: "package.json"
      },
      ...ordered.slice(0, 3).map((item) => ({
        kind: "source" as const,
        description: `${advisoryLabel(item.advisory)}: application code reaches ${item.via}.`,
        location: `${item.site.file}:${item.site.line}`
      }))
    ],
    reasoning: `Installed version ${entry.version} lies inside the advisory range${ordered.length === 1 ? "" : "s"}; the curated list of affected exports for ${ids.join(", ")} intersects what application code imports and uses.`
  };
}

function unreachedCandidate(unreached: Array<{ entry: Affected; why: string }>, lockfile: string | null): Candidate {
  const ordered = [...unreached].sort((a, b) => worstRank(b.entry) - worstRank(a.entry) || a.entry.name.localeCompare(b.entry.name));
  const runtime = ordered.filter((item) => !item.entry.dev);
  const advisoryCount = ordered.reduce((sum, item) => sum + item.entry.advisories.length, 0);
  const listed = ordered.slice(0, 12).map(
    (item) =>
      `${item.entry.name}@${item.entry.version}${item.entry.dev ? " (development)" : ""} — ${item.entry.advisories
        .slice(0, 3)
        .map(advisoryLabel)
        .join(", ")}${item.entry.advisories.length > 3 ? ` and ${item.entry.advisories.length - 3} more` : ""}; ${item.why}`
  );
  return {
    ruleId: "dependency-advisory",
    category: "dependency_with_known_advisory",
    title: `${ordered.length} installed package${ordered.length === 1 ? " is" : "s are"} inside a published advisory range but not reached from application code`,
    // Present but not reached: worth upgrading, not worth ranking beside a reachable
    // defect. Development-only packages do not run in production at all.
    severity: runtime.length > 0 ? "low" : "info",
    verification: "needs_review",
    summary: `${advisoryCount} advisor${advisoryCount === 1 ? "y applies" : "ies apply"} to versions ${lockfile ? `recorded in ${lockfile}` : "pinned in package.json"}, and in none of them does application code call the affected function: ${listed.join("; ")}${
      ordered.length > 12 ? `; and ${ordered.length - 12} more package(s)` : ""
    }. "Not reached" means this scan found no path from the application's own imports, not that no path exists — a package used by another package can still be exercised by a request.`,
    impact:
      runtime.length === 0
        ? "These are development dependencies, so the exposure is to the build and test environment rather than to production traffic."
        : "No direct call from application code to the affected functions was found. The exposure is through dependencies' own use of these packages, which this scan does not follow, and through future code that starts calling them.",
    remediation:
      "Upgrade each package past its advisory range in the normal course of maintenance, starting with runtime dependencies. For a package installed by another package, upgrade the parent or add an override. Record any version that cannot be upgraded together with why it is not reachable.",
    verificationPlan: "Re-read the lockfile after upgrading and confirm the resolved versions are outside every listed range; re-run the scan and confirm this item is gone.",
    taxonomy: ["CWE-1395", "CWE-1104", "OWASP-A06"],
    location: { file: "package.json", line: 1 },
    evidence: [
      {
        kind: "dependency",
        description: ordered
          .slice(0, 12)
          .map((item) => `${item.entry.name}@${item.entry.version}: ${item.entry.advisories.map(advisoryLabel).join(", ")}${item.entry.fixedIn ? `, fixed in ${item.entry.fixedIn}` : ""}`)
          .join("; "),
        location: lockfile ?? "package.json"
      }
    ],
    reasoning: `Installed versions were compared against the offline advisory snapshot (${ADVISORY_SNAPSHOT.advisories.length} advisories, newest record ${ADVISORY_SNAPSHOT.newestRecord ?? "unknown"}). Application imports and call sites were checked against each advisory's curated affected exports; none of these is reached.`
  };
}

function advisoryLabel(advisory: Advisory): string {
  return advisory.aliases[0] ? `${advisory.aliases[0]} (${advisory.id})` : advisory.id;
}

function worstRank(entry: Affected): number {
  return Math.max(...entry.advisories.map((advisory) => SEVERITY_RANK[advisory.severity]));
}

function fixedInPhrase(entry: Affected): string {
  return entry.fixedIn ? ` First release outside every range: ${entry.fixedIn}.` : "";
}

function earlier(a: Site, b: Site): boolean {
  return a.file < b.file || (a.file === b.file && a.line < b.line);
}

export const ADVISORY_COUNT = ADVISORY_SNAPSHOT.advisories.length;
