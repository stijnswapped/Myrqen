import { createReadStream } from "node:fs"
import fs from "node:fs/promises"
import path from "node:path"

import type { MedusaRequest, MedusaResponse } from "@medusajs/framework/http"
import type { EntityManager } from "@mikro-orm/postgresql"

import {
  MARKETPLACE_MANAGER,
  VendorDocument,
  VendorMember,
} from "../../../../../modules/marketplace/models"

/** Shared volume the document uploader writes scanned paperwork into. */
const DOCUMENT_ROOT =
  process.env.ATELIER_DOCUMENT_ROOT ?? "/var/lib/atelier/vendor-documents"

const CONTENT_TYPES: Record<string, string> = {
  ".pdf": "application/pdf",
  ".png": "image/png",
  ".jpg": "image/jpeg",
}

/**
 * Streams one page out of a scanned document. The dashboard viewer pages through
 * a document by asking for `?page=page-003.pdf`, taken from the manifest the
 * uploader wrote next to the pages.
 */
export const GET = async (req: MedusaRequest, res: MedusaResponse) => {
  const actorId = req.auth_context?.actor_id
  if (!actorId || req.auth_context?.actor_type !== "user") {
    return res.status(401).json({ message: "Not authenticated" })
  }

  const em = req.scope.resolve<EntityManager>(MARKETPLACE_MANAGER).fork()

  const document = await em.findOne(
    VendorDocument,
    { id: req.params.id },
    { populate: ["vendor"] }
  )
  if (!document) {
    return res.status(404).json({ message: "Document not found" })
  }

  // Atelier staff only ever see their own paperwork; platform finance is a
  // member of every atelier, which is how they get at all of it.
  const membership = await em.findOne(VendorMember, {
    vendor: document.vendor.id,
    user_id: actorId,
  })
  if (!membership) {
    return res.status(403).json({ message: "Not a member of this atelier" })
  }

  const page = String(req.query.page ?? "page-001.pdf")

  // storage_folder is generated by the uploader and `page` names a file inside
  // it, so the join stays under DOCUMENT_ROOT.
  const filePath = path.join(DOCUMENT_ROOT, document.storage_folder, page)

  const stat = await fs.stat(filePath).catch(() => null)
  if (!stat?.isFile()) {
    return res.status(404).json({ message: "Page not found" })
  }

  res.setHeader(
    "Content-Type",
    CONTENT_TYPES[path.extname(page).toLowerCase()] ?? "application/octet-stream"
  )
  res.setHeader("Content-Length", String(stat.size))
  res.setHeader("Cache-Control", "private, max-age=60")

  createReadStream(filePath).pipe(res)
}
