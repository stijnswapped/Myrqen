"""Invoice management for shop owners."""
from __future__ import annotations

from datetime import datetime, timezone

from flask import Blueprint, abort, jsonify, request
from flask_login import current_user, login_required

from app.audit import record_event
from app.models import Invoice, db

bp = Blueprint("invoices", __name__, url_prefix="/invoices")


@bp.get("/")
@login_required
def list_invoices():
    """Invoices issued by the signed-in user's shop."""
    invoices = (
        Invoice.query.filter_by(shop_id=current_user.shop_id)
        .order_by(Invoice.issued_at.desc())
        .limit(100)
        .all()
    )
    return jsonify([invoice.to_dict() for invoice in invoices])


@bp.post("/<int:invoice_id>/void")
@login_required
def void_invoice(invoice_id: int):
    """Void an issued invoice; a credit note is generated by the worker."""
    invoice = db.get_or_404(Invoice, invoice_id)
    if invoice.status != "issued":
        abort(409, description="only issued invoices can be voided")
    invoice.status = "void"
    invoice.voided_at = datetime.now(tz=timezone.utc)
    invoice.void_reason = (request.get_json(silent=True) or {}).get("reason", "")[:500]
    db.session.commit()
    record_event("invoice.voided", actor_id=current_user.id, invoice_id=invoice.id)
    return jsonify(invoice.to_dict())
